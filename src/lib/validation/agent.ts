/**
 * Проверка запроса к агенту.
 *
 * Организация обязательна: от неё зависит история поставки, а диалог
 * пользователя, состоящего в двух организациях, иначе смешивал бы их.
 * Релиз необязателен — вопрос может быть и об истории, — но если он
 * назван, агент получит его в первом же обращении к инструменту.
 */

import { z } from 'zod';

export const agentChatSchema = z.object({
  orgId: z.string().uuid('Ожидается идентификатор организации'),
  releaseId: z.string().uuid().optional(),
  /** Продолжение диалога. Без него начинается новый. */
  sessionId: z.string().uuid().optional(),
  /*
    Потолок на длину вопроса — не про удобство. Вопрос уходит в модель
    как есть, и без ограничения он становится способом залить в контекст
    что угодно за счёт владельца ключа.
  */
  message: z
    .string()
    .trim()
    .min(1, 'Вопрос пустой')
    .max(2000, 'Вопрос слишком длинный: сформулируйте короче'),
});

export type AgentChatInput = z.infer<typeof agentChatSchema>;
