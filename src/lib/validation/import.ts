/**
 * Проверка полей загрузки файла.
 *
 * Файл приходит формой (multipart), а не JSON, поэтому схема проверяет
 * только сопутствующие поля: сам файл схемой не описать, и его размер и
 * формат проверяются в маршруте, где он уже прочитан.
 */

import { z } from 'zod';

import { IMPORT_FORMATS } from '@/lib/import/parse';

export const importFieldsSchema = z.object({
  projectId: z.string().uuid('Ожидается идентификатор проекта'),
  /** Формат можно назвать явно — иначе он определяется по имени файла. */
  format: z.enum(IMPORT_FORMATS, { message: 'Поддерживаются только csv и json' }).optional(),
  /**
   * Пробный прогон: разобрать, проверить и отчитаться, ничего не записав.
   *
   * Нужен не для удобства. Импорт меняет состав релизов, а значит и риск,
   * и человеку разумно сначала увидеть отчёт об ошибках, а потом решать.
   * Без пробного прогона единственный способ проверить файл — применить
   * его.
   */
  dryRun: z
    .enum(['true', 'false', '1', '0'])
    .transform((v) => v === 'true' || v === '1')
    .optional()
    .default(false),
});

export type ImportFields = z.infer<typeof importFieldsSchema>;
