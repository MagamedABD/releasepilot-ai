/**
 * Перевод ошибок Supabase Auth в сообщения для человека.
 *
 * Показывать пользователю «Invalid login credentials» нельзя по двум
 * причинам: он не обязан знать английский и уж точно не обязан понимать
 * внутренние коды чужого сервиса.
 *
 * Отдельно про формулировки: при неверной паре почта-пароль сообщение
 * намеренно не уточняет, что именно не подошло. «Такой почты нет»
 * превращает форму входа в способ проверять, зарегистрирован ли
 * конкретный человек в системе.
 */

import { AuthError } from '@supabase/supabase-js';

const BY_CODE: Record<string, string> = {
  invalid_credentials: 'Неверная почта или пароль',
  email_not_confirmed: 'Почта не подтверждена — проверьте письмо',
  user_already_exists: 'Пользователь с такой почтой уже зарегистрирован',
  email_exists: 'Пользователь с такой почтой уже зарегистрирован',
  weak_password: 'Пароль слишком простой',
  over_request_rate_limit: 'Слишком много попыток. Подождите минуту и повторите',
  over_email_send_rate_limit: 'Письма отправляются слишком часто. Подождите немного',
  signup_disabled: 'Регистрация временно закрыта',
  validation_failed: 'Проверьте правильность заполнения полей',
  // Supabase проверяет адрес строже, чем zod: домены вроде .test и .local
  // он отклоняет. Формально адрес написан верно, но письмо слать некуда.
  email_address_invalid: 'На этот адрес не получится отправить письмо. Проверьте домен',
  email_address_not_authorized: 'На этот адрес отправка писем не разрешена',
  otp_expired: 'Ссылка из письма больше не действует',
  same_password: 'Новый пароль совпадает со старым',
};

/**
 * @param context откуда пришла ошибка. Нужен только для запасного разбора
 *   по статусу: статус 400 на входе почти всегда значит неверную пару
 *   почта-пароль, а на регистрации — что угодно, кроме неё. Сказать там
 *   «неверный пароль» значит отправить человека чинить то, что не сломано.
 */
export function translateAuthError(error: unknown, context: 'login' | 'signup' = 'login'): string {
  if (error instanceof AuthError) {
    if (error.code && BY_CODE[error.code]) return BY_CODE[error.code];

    // Часть ошибок приходит без кода — разбираем по статусу
    if (error.status === 429) return BY_CODE.over_request_rate_limit;
    if (error.status === 400) {
      return context === 'login'
        ? 'Неверная почта или пароль'
        : 'Проверьте правильность заполнения полей';
    }
  }

  // Сеть недоступна, сервис лежит, что-то непредвиденное. Пользователю
  // нужно понять, что делать, а не что именно сломалось.
  return 'Не удалось связаться с сервисом. Попробуйте ещё раз через минуту';
}
