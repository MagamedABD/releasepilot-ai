/**
 * Анонимизация при импорте из корпоративного источника (FR-42, ADR-002).
 *
 * Что именно защищается. Риск в уставе назван прямо: утечка корпоративных
 * данных в публичный деплой. Утекают не числа — часы, статусы и связи
 * ничего не рассказывают, — а текст: название задачи «Интеграция с
 * процессингом Альфы», ключ очереди с именем клиента, фамилия
 * исполнителя. Поэтому анонимизация убирает текст и оставляет структуру:
 * оценки, статусы, приоритеты, зависимости и команды остаются как есть, и
 * расчёт риска по ним получается точно тот же.
 *
 * Как это устроено. Псевдоним выводится из ключа задачи и идентификатора
 * организации через SHA-256. Отсюда два свойства, и оба нужны:
 *
 * 1. **Устойчивость.** Повторный импорт даёт тот же псевдоним, поэтому
 *    задача обновляется, а не дублируется. Случайный псевдоним при каждой
 *    загрузке заводил бы копии.
 * 2. **Несвязываемость между организациями.** Один и тот же ключ в разных
 *    организациях даёт разные псевдонимы: соль — идентификатор
 *    организации.
 *
 * Чего анонимизация **не** делает, и это важнее того, что делает:
 *
 * — Она не обратима без исходных данных, но и не является защитой от
 *   того, у кого исходный трекер есть: зная список ключей, сопоставить
 *   псевдонимы можно перебором. Это не шифрование, а снятие текста.
 * — Она не трогает имена команд. Команды сопоставляются по имени с уже
 *   существующими в организации, и псевдоним разорвал бы сопоставление —
 *   задачи остались бы без команды, а это тихо ломает расчёт загрузки
 *   (см. правило в `plan.ts`).
 */

import { createHash } from 'node:crypto';

/**
 * Короткий устойчивый псевдоним.
 *
 * Шесть шестнадцатеричных знаков — 16 миллионов значений. Для релиза из
 * трёхсот задач вероятность совпадения около 0.3%, и совпадение не
 * опасно: ключ после анонимизации уникален в пределах проекта по
 * ограничению базы, и вторая задача с тем же псевдонимом будет
 * отклонена отчётом, а не затрёт первую.
 */
export function pseudonym(orgId: string, key: string): string {
  return createHash('sha256').update(`${orgId}:${key}`).digest('hex').slice(0, 6).toUpperCase();
}

export type AnonymizedFields = {
  key: string;
  title: string;
  description: null;
};

/**
 * Задача без корпоративного текста.
 *
 * Название заменяется, а не вырезается: пустое название не прошло бы
 * проверку, а «задача» без различий превратила бы список в сто
 * одинаковых строк. Псевдоним в названии оставляет задачи различимыми —
 * этого достаточно, чтобы читать блокеры и критическую цепочку.
 *
 * Описание удаляется целиком. В нём нет ничего, что нужно расчёту, а
 * рисков больше всего: именно там оказываются имена, ссылки на внутренние
 * системы и переписка.
 */
export function anonymizeTask(orgId: string, key: string): AnonymizedFields {
  const alias = pseudonym(orgId, key);
  return {
    key: `ANON-${alias}`,
    title: `Задача ${alias}`,
    description: null,
  };
}
