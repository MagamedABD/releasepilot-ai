/**
 * Выборка задач по фильтрам.
 *
 * Живёт отдельным модулем, потому что читателей у неё двое: маршрут
 * `/api/tasks` и экран задач. Пока фильтры собирались в обработчике
 * маршрута, у страницы был выбор — позвать свой же HTTP-эндпоинт
 * (лишний сетевой круг и передача cookie ради данных, до которых
 * серверный компонент дотягивается напрямую) или повторить цепочку
 * условий у себя. Второе хуже: два набора фильтров расходятся не сразу,
 * а через месяц, когда новый фильтр добавят в одном месте и забудут
 * в другом, и страница начнёт молча отвечать не на тот вопрос.
 *
 * Поэтому здесь один источник правды на условия, порядок и страницу.
 * Проекция при этом одна и та же — `*`: подставлять её параметром
 * значит потерять типы, ради которых схема базы и генерировалась.
 */

import type { SupabaseClient } from '@supabase/supabase-js';

import type { Database } from '@/lib/database.types';
import type { TaskQuery } from '@/lib/validation/task';

type Client = SupabaseClient<Database>;
export type TaskRow = Database['public']['Tables']['tasks']['Row'];

export type TaskPage = {
  rows: TaskRow[];
  /** Всего задач под фильтр, без учёта страницы. */
  total: number;
  /**
   * Момент, на который выборка верна.
   *
   * Отдаётся вместе с данными, потому что часть ответов на них считается
   * от «сейчас»: возраст блокировки — это `blocked_since` и текущее
   * время, и время здесь такой же вход, как сама строка. Если бы каждый
   * компонент смотрел на часы сам, таблица и карточки на одной странице
   * считали бы возраст от двух разных моментов, а «застарелость» блокера
   * могла бы переключиться посреди отрисовки.
   *
   * Заодно это снимает чтение часов с отрисовки: компонент обязан быть
   * чистым, а `Date.now()` в нём — источник результата, который меняется
   * сам собой.
   */
  at: number;
  error: { code?: string; message?: string } | null;
};

/**
 * Страница задач под фильтр.
 *
 * Организация в условиях не участвует, и это не забывчивость. Клиент
 * ходит от лица пользователя (anon-ключ плюс его сессия), доступ
 * разграничивают политики RLS. Условие `org_id = …` выглядело бы
 * защитой, не будучи ею: стоит забыть его в следующей выборке, и данные
 * потекут. Защита обязана быть там, где её нельзя забыть.
 */
export async function selectTasks(supabase: Client, q: TaskQuery): Promise<TaskPage> {
  let query = supabase.from('tasks').select('*', { count: 'exact' });

  if (q.orgId) query = query.eq('org_id', q.orgId);
  if (q.releaseId) query = query.eq('release_id', q.releaseId);
  if (q.projectId) query = query.eq('project_id', q.projectId);
  if (q.teamId) query = query.eq('team_id', q.teamId);
  if (q.status) query = query.eq('status', q.status);
  if (q.priority) query = query.eq('priority', q.priority);

  // Блокировка — не статус, а отдельная ось: задача бывает заблокирована
  // в любом статусе, кроме завершённых. Признак хранится отметкой времени,
  // поэтому фильтр идёт по её наличию.
  if (q.blocked !== undefined) {
    query = q.blocked ? query.not('blocked_since', 'is', null) : query.is('blocked_since', null);
  }

  if (q.q) {
    // Экранируем запятую и скобки: в синтаксисе PostgREST они разделяют
    // условия, и строка поиска с запятой иначе сломала бы разбор фильтра.
    const safe = q.q.replace(/[,()\\]/g, ' ');
    query = query.ilike('title', `%${safe}%`);
  }

  /*
    Порядок: приоритет, затем свежесть.

    По приоритету — потому что список задач открывают с вопросом «чем
    заниматься», а не «что появилось». P0 в перечислении базы объявлен
    первым, и Postgres сортирует enum по порядку объявления, а не по
    алфавиту, — то есть P0 действительно окажется сверху. Будь это
    текстовая колонка, порядок случайно совпал бы с нужным, и сортировка
    сломалась бы на первом же приоритете вида «P10».
  */
  const { data, error, count } = await query
    .order('priority')
    .order('created_at', { ascending: false })
    .range(q.offset, q.offset + q.limit - 1);

  return { rows: data ?? [], total: count ?? 0, at: Date.now(), error };
}
