/**
 * Подписи диалога с агентом.
 *
 * Вызовы инструментов показываются пользователю, и это не украшение
 * (docs/05-ui-concept.md, экран 5): менеджер должен видеть, на основании
 * чего получен ответ, иначе рекомендации нечем доверять. А «get_team_load»
 * в интерфейсе — это не «видно», а «написано по-английски».
 */

/** Что делает инструмент — глаголом в первом лице, как это читается в строке. */
const TOOL_LABELS: Record<string, string> = {
  get_release_overview: 'смотрю состояние релиза',
  get_team_load: 'смотрю загрузку команд',
  get_blockers: 'смотрю блокеры',
  get_critical_chain: 'считаю критическую цепочку',
  list_tasks: 'выбираю задачи',
  forecast_completion: 'считаю прогноз выпуска',
  simulate_scenario: 'считаю сценарий',
  suggest_scenario: 'подбираю, что перенести',
  get_release_history: 'смотрю историю релизов',
  propose_scenario: 'оформляю предложение',
};

export function toolLabel(name: string): string {
  // Неизвестное имя показывается как есть: это значит, что инструмент
  // добавили, а подпись забыли, и прятать такое за «работаю» — значит
  // прятать собственную недоделку от себя же.
  return TOOL_LABELS[name] ?? name;
}

/** Отказ инструмента тоже виден: ответ, собранный на ошибках, подозрителен. */
export function toolFailureLabel(name: string): string {
  return `${toolLabel(name)} — не удалось`;
}

