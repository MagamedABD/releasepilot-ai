/**
 * Адрес организации из её названия.
 *
 * Название вводят по-русски — «Платёжный шлюз», — а адрес обязан быть
 * латиницей: он попадает в URL, в ссылки на релизы, в письма. Просить
 * человека придумать латинское имя отдельным полем значит просить его
 * сделать работу, которую машина делает лучше.
 *
 * Перевод односторонний: «щ» становится «sch», обратно уже не разобрать.
 * Это нормально — адрес не должен читаться обратно в название, он должен
 * быть коротким, устойчивым и уникальным.
 */

const MAP: Record<string, string> = {
  а: 'a', б: 'b', в: 'v', г: 'g', д: 'd', е: 'e', ё: 'e', ж: 'zh',
  з: 'z', и: 'i', й: 'y', к: 'k', л: 'l', м: 'm', н: 'n', о: 'o',
  п: 'p', р: 'r', с: 's', т: 't', у: 'u', ф: 'f', х: 'h', ц: 'ts',
  ч: 'ch', ш: 'sh', щ: 'sch', ъ: '', ы: 'y', ь: '', э: 'e', ю: 'yu',
  я: 'ya',
};

export function slugify(value: string): string {
  return value
    .toLowerCase()
    .split('')
    .map((ch) => MAP[ch] ?? ch)
    .join('')
    // Всё, что не латиница и не цифра, становится дефисом: пробелы,
    // кавычки, скобки, эмодзи и буквы языков, которых нет в таблице.
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/^-+|-+$/g, '')
    .slice(0, 40)
    // Обрезка по длине могла оставить дефис на конце
    .replace(/-+$/, '');
}
