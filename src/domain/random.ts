/**
 * Случайность, которую можно воспроизвести.
 *
 * `Math.random` здесь не подходит по двум причинам, и вторая важнее первой.
 * Первая — тесты: прогноз, дающий каждый раз другое число, проверить нечем.
 * Вторая — доверие: менеджер, обновивший страницу и увидевший 71% вместо
 * 68%, перестаёт верить не проценту, а системе. Вероятность обязана
 * меняться от данных, а не от нажатия F5.
 *
 * Поэтому генератор свой, с явным зерном (ADR-001, §6).
 */

/** Последовательность равномерных чисел в [0, 1). */
export type Random = () => number;

/**
 * Mulberry32: 32-битный счётчик с перемешиванием.
 *
 * Выбран не за качество — для криптографии он негоден, — а за три
 * свойства: одно целое состояния, одинаковый результат в любом движке
 * (всё через `Math.imul`, без 64-битной арифметики) и период 2³²,
 * которого хватает на 5000 итераций с запасом в шесть порядков.
 */
export function mulberry32(seed: number): Random {
  let state = seed >>> 0;

  return () => {
    state = (state + 0x6d2b79f5) >>> 0;
    let t = state;
    t = Math.imul(t ^ (t >>> 15), t | 1);
    t ^= t + Math.imul(t ^ (t >>> 7), t | 61);
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}

/**
 * Зерно из строки (FNV-1a, 32 бита).
 *
 * Нужно, чтобы зерном служил идентификатор релиза: тогда прогноз
 * воспроизводим сам по себе, без передачи зерна снаружи, а два разных
 * релиза не получают одну и ту же последовательность — иначе их прогнозы
 * ошибались бы синхронно.
 */
export function seedFromString(value: string): number {
  let hash = 0x811c9dc5;
  for (let i = 0; i < value.length; i++) {
    hash ^= value.charCodeAt(i);
    hash = Math.imul(hash, 0x01000193);
  }
  // Ноль — допустимое состояние Mulberry32, но зерно 0 у пустой строки
  // выглядело бы как «зерно не задано». Смещаем.
  return (hash >>> 0) || 1;
}

/**
 * Нормальное N(0,1) методом Бокса — Мюллера.
 *
 * Второе значение пары намеренно не кэшируется. Кэш сделал бы результат
 * зависимым от того, сколько раз функцию вызвали раньше: тот же генератор,
 * вызванный в другом порядке, дал бы другие числа, и воспроизводимость,
 * ради которой всё это писалось, держалась бы на порядке вызовов.
 */
export function gaussian(random: Random): number {
  // Ноль под логарифмом даёт −∞, поэтому берём число из (0, 1].
  const u = 1 - random();
  const v = random();
  return Math.sqrt(-2 * Math.log(u)) * Math.cos(2 * Math.PI * v);
}

/**
 * Гамма-распределение, метод Марсальи — Цанга.
 *
 * Нужно лишь как строительный материал для бета-распределения: прямого
 * способа получить бета-величину из равномерной нет, а через две
 * гамма-величины — есть.
 */
export function gammaVariate(random: Random, shape: number): number {
  if (!(shape > 0)) throw new Error(`Параметр формы должен быть положительным: ${shape}`);

  // Для shape < 1 метод неприменим напрямую; используется тождество
  // Gamma(a) = Gamma(a+1) · U^(1/a).
  if (shape < 1) {
    const u = 1 - random();
    return gammaVariate(random, shape + 1) * Math.pow(u, 1 / shape);
  }

  const d = shape - 1 / 3;
  const c = 1 / Math.sqrt(9 * d);

  // Цикл с отклонением: в среднем чуть больше одной попытки, но
  // теоретической верхней границы у числа попыток нет. Счётчик — защита
  // не от математики, а от испорченного генератора, который вернул бы
  // константу и вечно не проходил проверку.
  for (let attempt = 0; attempt < 1000; attempt++) {
    let x: number;
    let v: number;
    do {
      x = gaussian(random);
      v = 1 + c * x;
    } while (v <= 0);

    v = v * v * v;
    const u = random();

    if (u < 1 - 0.0331 * x * x * x * x) return d * v;
    if (Math.log(u) < 0.5 * x * x + d * (1 - v + Math.log(v))) return d * v;
  }

  throw new Error('Генератор гамма-величин не сошёлся');
}

/** Бета-распределение через две гамма-величины. */
export function betaVariate(random: Random, alpha: number, beta: number): number {
  const a = gammaVariate(random, alpha);
  const b = gammaVariate(random, beta);
  const sum = a + b;
  // Оба нуля одновременно практически невозможны, но деление на ноль
  // испортило бы всю итерацию, а не одну задачу.
  return sum > 0 ? a / sum : 0.5;
}

/**
 * Параметры Beta-PERT по трём точкам.
 *
 * Треугольное распределение здесь было бы проще, но у него сосредоточена
 * масса у краёв: срок «в два раза больше оценки» получался бы почти так же
 * часто, как срок «как оценили». Beta-PERT — тот же трёхточечный вход, но
 * с массой вокруг вероятного значения, а λ задаёт, насколько уверенно.
 *
 * Классическое λ = 4 даёт привычную среднюю `(o + 4m + p) / 6`.
 */
export function pertShape(
  optimistic: number,
  likely: number,
  pessimistic: number,
  lambda: number,
): { alpha: number; beta: number } {
  const span = pessimistic - optimistic;
  // Вырожденный случай: три точки совпали, разброса нет. Симметричные
  // единицы дают равномерное распределение, и на нулевом размахе это
  // безразлично — важно не поделить на ноль.
  if (span <= 0) return { alpha: 1, beta: 1 };

  return {
    alpha: 1 + (lambda * (likely - optimistic)) / span,
    beta: 1 + (lambda * (pessimistic - likely)) / span,
  };
}
