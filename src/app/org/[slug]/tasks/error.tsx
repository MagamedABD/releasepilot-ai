'use client';

/**
 * Состояние ошибки на экране задач.
 *
 * Клиентский компонент по необходимости, а не по выбору: `reset` —
 * функция, и передать её из серверного компонента через границу нельзя.
 *
 * Объект ошибки сюда приходит, но на экран не идёт (NFR-08): пользователю
 * он ничего не объясняет, а постороннему рассказывает об устройстве
 * системы. Кнопка повтора важнее текста — сбой выборки чаще всего сетевой
 * и проходит сам.
 */

import { ErrorState } from '@/components/states';

export default function Error({ reset }: { error: Error; reset: () => void }) {
  return (
    <div className="mx-auto flex w-full max-w-6xl flex-1 flex-col justify-center px-4 py-10">
      <ErrorState
        title="Не удалось загрузить задачи"
        description="Список не пришёл — похоже, пропала связь с базой. Фильтры сохранены в адресе, так что после повтора вы окажетесь там же."
        onRetry={reset}
      />
    </div>
  );
}
